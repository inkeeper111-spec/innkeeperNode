import mongoose from 'mongoose';

const poItemSchema = new mongoose.Schema({
  itemId: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'InventoryItem'
  },
  itemName: {
    type: String,
    required: true
  },
  quantity: {
    type: Number,
    required: true,
    min: 0.00000001
  },
  receivedQuantity: { type: Number, min: 0, default: 0 },
  unit: { type: String, default: '' },
  unitId: { type: mongoose.Schema.Types.ObjectId, ref: 'Unit', default: null },
  purchasePackageId: { type: mongoose.Schema.Types.ObjectId, default: null },
  packageNameSnapshot: { type: String, trim: true, default: '' },
  unitNameSnapshot: { type: String, default: '' },
  unitSymbolSnapshot: { type: String, default: '' },
  conversionFactor: { type: Number, min: 0.000000001, default: 1 },
  baseUnit: { type: String, default: '' },
  baseUnitId: { type: mongoose.Schema.Types.ObjectId, ref: 'Unit', default: null },
  baseUnitNameSnapshot: { type: String, default: '' },
  baseUnitSymbolSnapshot: { type: String, default: '' },
  unitCost: {
    type: Number,
    required: true,
    min: 0
  },
  totalAmount: {
    type: Number,
    required: true
  }
}, { _id: false });

const purchaseOrderSchema = new mongoose.Schema({
  hotelId: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'Hotel',
    required: true,
    index: true
  },
  propertyId: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'Property',
    required: true,
    index: true
  },
  poNumber: {
    type: String,
    required: true,
    unique: true,
    index: true
  },
  vendorId: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'Vendor',
    default: null
  },
  autoGenerated: { type: Boolean, default: false, index: true },
  autoReorderItemId: { type: mongoose.Schema.Types.ObjectId, ref: 'InventoryItem', default: null },
  items: [poItemSchema],
  totalAmount: {
    type: Number,
    required: true
  },
  status: {
    type: String,
    enum: ['draft', 'pending_approval', 'approved', 'ordered', 'partially_received', 'received', 'cancelled', 'rejected'],
    default: 'draft',
    index: true
  },
  expectedDeliveryDate: Date,
  department: { type: String, trim: true, default: '' },
  purchaseRequestId: { type: mongoose.Schema.Types.ObjectId, ref: 'DepartmentRequest', default: null },
  taxAmount: { type: Number, min: 0, default: 0 },
  discountAmount: { type: Number, min: 0, default: 0 },
  subtotal: { type: Number, min: 0, default: 0 },
  invoiceAttachment: { type: String, default: '' },
  approvedBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User', default: null },
  approvedAt: Date,
  receivingHistory: [{
    type: mongoose.Schema.Types.ObjectId,
    ref: 'GoodsReceipt'
  }],
  receivedDate: Date,
  notes: {
    type: String,
    default: ''
  },
  createdBy: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User'
  }
}, {
  timestamps: true
});

purchaseOrderSchema.index(
  { hotelId: 1, propertyId: 1, autoReorderItemId: 1 },
  {
    unique: true,
    partialFilterExpression: { autoReorderItemId: { $type: 'objectId' } }
  }
);

export const PurchaseOrder = mongoose.models.PurchaseOrder || mongoose.model('PurchaseOrder', purchaseOrderSchema);
